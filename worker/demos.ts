import type { Context } from "hono";
import { demos } from "../shared/demos";
import { AppEnv, Problem, id, now, str } from "./types";
import { one, insert, event } from "./db";
import { mapStatements, taskStatements } from "./learning";
import { defaultDetails } from "./contracts";
export async function launchDemo(c: Context<AppEnv>) {
  const scenario = demos.find((s) => s.id === c.req.param("id"));
  if (!scenario)
    throw new Problem(
      404,
      "DEMO_NOT_FOUND",
      "Choose an available demo scenario.",
    );
  const actor = c.get("actor"),
    db = c.env.DB;
  const existing = await one(
    db,
    "SELECT id FROM goals WHERE user_id=? AND json_extract(details,'$.demo_id')=?",
    actor.id,
    scenario.id,
  );
  if (existing) {
    const t = await one(
      db,
      "SELECT id FROM tasks WHERE user_id=? AND goal_id=? ORDER BY created_at LIMIT 1",
      actor.id,
      existing.id,
    );
    return c.json({ goalId: existing.id, taskId: t?.id, reused: true });
  }
  const goalId = id(),
    time = now(),
    g = {
      id: goalId,
      version: 1,
      title: scenario.label + " demo",
      description: scenario.description,
    };
  const m = mapStatements(
    db,
    actor.id,
    g,
    {
      rationale:
        "Illustrative, human-authored demo path. This demonstrates the workflow and does not establish the visitor’s ability.",
      skills: scenario.skills as any,
    },
    "Explicit demo scenario",
  );
  const t = taskStatements(
    db,
    actor.id,
    g,
    { task: scenario.task, rationale: "A human-authored demonstration task." },
    "project",
    scenario.skills as any,
    [],
  );
  const attemptId = id(),
    evaluationId = id(),
    portfolioId = id();
  const result = {
    summary:
      "This is a scripted example showing what specific, encouraging feedback can look like. It was not generated by a model and is not an assessment of your ability.",
    strengths: [
      {
        observation: scenario.sample.strength,
        quote: scenario.sample.quote,
        why_it_matters:
          "The reasoning makes the choice inspectable and gives the next attempt a clear starting point.",
      },
    ],
    criteria: scenario.task.criteria.map((c) => ({
      criterion_id: c.id,
      status: "partial",
      quote: "",
      explanation:
        "Illustrative standard. A real assessment needs your own submission and a connected model or an appropriate qualified reviewer.",
    })),
    claims: [],
    gaps: ["Try your own version and explain what you changed."],
    misconceptions: [],
    not_demonstrated: ["Your independent ability has not been assessed."],
    uncertainty:
      "All content in this scenario is an illustrative sample, not an observed learner performance.",
    next_step: scenario.sample.next,
    requires_human_review: scenario.task.verification_method !== "ai_rubric",
    domain_boundary: scenario.task.verification_boundary,
    objective_checks: [
      {
        name: "Code or physical performance executed/observed",
        passed: null,
        note: "No execution or real-world observation took place.",
      },
    ],
    independent: false,
    verification_passed: false,
    assistance: { declared: "example", platform_hints: 0 },
    assessment_type: "Scripted demo feedback",
    is_demo: true,
  };
  await db.batch([
    insert(db, "goals", {
      id: goalId,
      user_id: actor.id,
      title: "Demo · " + scenario.label,
      description: scenario.description,
      details: str({
        ...defaultDetails,
        outcome: scenario.outcome,
        success_criteria: scenario.skills[0].standards,
        is_demo: true,
        demo_id: scenario.id,
        entry_type:
          scenario.id === "coffee-chat"
            ? "direction"
            : scenario.id === "python"
              ? "project"
              : "skill",
      }),
      status: "active",
      stage: "discover",
      confirmed: 1,
      version: 1,
      created_at: time,
      updated_at: time,
    }),
    ...m.writes,
    ...t.writes,
    insert(db, "attempts", {
      id: attemptId,
      user_id: actor.id,
      task_id: t.taskId,
      version: 1,
      kind: scenario.sample.kind,
      content: scenario.sample.content,
      explanation: scenario.sample.explanation,
      links: "[]",
      file_ids: "[]",
      status: "submitted",
      revision: 1,
      assistance: str({
        declared: "example",
        platform_hints: 0,
        is_demo: true,
      }),
      created_at: time,
      submitted_at: time,
    }),
    insert(db, "evaluations", {
      id: evaluationId,
      user_id: actor.id,
      goal_id: goalId,
      task_id: t.taskId,
      attempt_id: attemptId,
      result: str(result),
      passed: 0,
      requires_review: 0,
      review_status: "none",
      created_at: time,
    }),
    insert(db, "portfolio", {
      id: portfolioId,
      user_id: actor.id,
      goal_id: goalId,
      evaluation_id: evaluationId,
      attempt_id: attemptId,
      title: "Demo · " + scenario.task.title,
      visibility: "private",
      created_at: time,
    }),
    event(db, actor.id, goalId, "demo_started", {
      scenario: scenario.id,
      notice: "Explicit illustrative data, not learner evidence",
    }),
  ]);
  return c.json({ goalId, taskId: t.taskId }, 201);
}
